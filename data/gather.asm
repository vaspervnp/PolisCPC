; gather.asm — οι πόροι που μαζεύονται, και τα ψηφία του HUD (M6).
; ΠΑΡΑΓΕΤΑΙ από src/make_map.py — μην το πειράζεις με το χέρι.

; ανά θέση στο RESOURCES: είδος (0 τροφή, 1 ξύλο, 2 χρυσό, 3 πέτρα,
; 255 κανένα), ποσό ανά πηγή, και ο πόρος που μένει όταν αδειάσει
res_kind:   db 255,1,1,1,255,0,255,2,3,255,0,0,0,255,0,255
res_amount: dw 0,120,120,100,0,150,0,200,250,0,200,450,100,0,40,0
res_spent:  db 0,4,4,4,0,6,0,9,9,0,0,0,0,0,0,0

; η μπάρα: το byte κάθε αριθμού (4 ψηφία) και η γραμμή του HUD
BAR_Y       equ 6
bar_x:      db 5,17,29,41,53,65

; η κάρτα του επιλεγμένου κτιρίου: ψηφίο και μπάρα προόδου
CARD_X      equ 13
CARD_Y      equ 29
CARD_BY     equ 37
CARD_FULL   equ #F3
CARD_HALF   equ #E2
CARD_EMPTY  equ #C0

; μονάδα πίσω από κτίριο: το περίγραμμα, στο pen της ομάδας
OUTLINE     equ #0C

; 11 ψηφία (0-9, κενό) x 5 γραμμές x 2 bytes: στην κύρια RAM,
; στις γραμμές του HUD που δεν φαίνονται (από το data/digits.bin,
; στο τέλος του hud_z — screen.asm, hud_init)
digits      equ #4790
DIGITS_LEN  equ 110
