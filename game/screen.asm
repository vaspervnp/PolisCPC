; screen.asm — η οθόνη που κυλάει, και το HUD που ΔΕΝ κυλάει. M2.
;
; Η ΚΥΛΙΣΗ ΕΙΝΑΙ ΤΟΥ CRTC
;
;   Η διεύθυνση αρχής (R12/R13, σε ΛΕΞΕΙΣ των 2 bytes) μετακινεί όλη την
;   εικόνα. Το `scr_s` είναι αυτή η μετατόπιση, 0..1023:
;
;       +1    -> 2 bytes = 4 pixels δεξιά       (cam_x += 2)
;       +40   -> μία σειρά = 8 γραμμές κάτω     (cam_y += 8)
;
;   Η μνήμη του CRTC είναι 8 «οκτάδες» των 2 KB (μία ανά γραμμή μέσα στη
;   σειρά χαρακτήρων), και μέσα στην καθεμία η διεύθυνση ΤΥΛΙΓΕΤΑΙ στα 2 KB.
;   Άρα η γραμμή y της οθόνης είναι στο
;
;       #C000 + (y & 7) * #800 + ((2*scr_s + (y >> 3) * 80) AND #7FF)
;
;   και ΜΙΑ γραμμή μπορεί να σπάει στη μέση, στο όριο των 2 KB. Όποια
;   ρουτίνα γράφει bytes με `inc de` το χειρίζεται (`wrapde`).
;
; ΤΟ HUD ΜΕΝΕΙ ΑΚΙΝΗΤΟ: ΔΥΟ ΚΑΡΕ CRTC ΣΕ ΕΝΑ (split-screen / rupture)
;
;   Το κανονικό καρέ (39 σειρές = 312 γραμμές) σπάει σε δύο:
;
;     Α  σειρές 0-17   ο χάρτης, 144 γραμμές, αρχή #C000 + scr_s
;     Β  σειρές 0-20   το HUD (7 σειρές = 56 γραμμές) και το περιθώριο, αρχή
;                      #4000 — η ΚΥΡΙΑ RAM εκεί, που το video τη διαβάζει
;                      πάντα, ακόμα κι όταν ο CPU βλέπει μια τράπεζα C4-C7
;
;   Οι καταχωρητές γράφονται μέσα στη διακοπή των 300 Hz. Ο gate array
;   δίνει διακοπή κάθε 52 γραμμές, συγχρονισμένη στο VSYNC (γραμμή 240):
;
;     n=0  γρ. ~242 (μέσα στο VSYNC: έτσι αναγνωρίζεται)
;     n=2  γρ. ~34   μέσα στο Α (σειρά 4):  το Α τελειώνει στη σειρά 17,
;                    χωρίς VSYNC· η αρχή του Β = HUD
;     n=5  γρ. ~190  μέσα στο Β (σειρά 5):  το Β έχει 21 σειρές, 7 ορατές,
;                    VSYNC στη σειρά 12 (= γραμμή 240, όπως πριν)· η αρχή
;                    του επόμενου Α = scr_s
;
;   Κάθε R4 γράφεται ΜΕΣΑ στο καρέ που αφορά και ΠΡΙΝ φτάσει εκεί ο μετρητής
;   σειρών: αν ο μετρητής έχει περάσει ήδη την τιμή, το καρέ δεν τελειώνει
;   ποτέ. Το R12/R13 γράφεται στο ΑΛΛΟ καρέ: διαβάζεται στην αρχή του καρέ.
;   Το VSYNC μένει στη γραμμή 240, άρα και οι διακοπές μένουν στη θέση τους.

HUD_PAGE    equ #4000

; Η διακοπή. Ο κύριος κώδικας χρησιμοποιεί και τους alt καταχωρητές και το
; IX: εδώ δεν αγγίζονται. Τρέχει 300 φορές το δευτερόλεπτο, άρα κοστίζει:
; οι 4 από τις 6 βγαίνουν αμέσως, οι 2 του split γράφουν 4 καταχωρητές.
;
; ΤΟ R6 ΔΕΝ ΑΛΛΑΖΕΙ. Είναι 127 και για τα δύο καρέ: όλες οι σειρές «φαίνονται».
; Στο Β οι σειρές 7-20 δείχνουν τη σελίδα του HUD πέρα από το HUD, που είναι
; μηδενικά — μαύρο, όσο και το περιθώριο. Έτσι το Β δεν έχει ούτε ένα
; στενό παράθυρο: το R7=12 θέλει να γραφτεί πριν τη σειρά 12, το R4=20 πριν
; την 20, και η διακοπή έρχεται στη σειρά 6.
int_handler:
        push af
        push bc
        ld b,PPI_B
        in a,(c)
        rra
        jr nc,.count
        ld a,(int_t)            ; ο μετρητής των 300 Hz (units.asm: χρόνος)
        inc a
        ld (int_t),a
        xor a                   ; μέσα στο VSYNC: η πρώτη του καρέ
        ld (int_n),a
        ld a,(split_req)        ; το split ανοίγει ΜΟΝΟ εδώ: αν ανοίξει σε
        ld (split_on),a         ; τυχαία στιγμή, το R4=20 του Β μπορεί να
        pop bc                  ; πέσει σε σειρά > 20 και το καρέ δεν
        pop af                  ; τελειώνει ώσπου να τυλίξει ο μετρητής
        ei
        ret
.count: ld a,(int_t)
        inc a
        ld (int_t),a
        ld a,(int_n)
        inc a
        ld (int_n),a
        cp 2
        jr z,.fa
        cp 5
        jr z,.fb
.out:   pop bc
        pop af
        ei
        ret
.fb:    ld a,(split_on)         ; μέσα στο Β (σειρά ~6): το Β και το επόμενο Α
        or a
        jr z,.out
        ld bc,#BC04             ; R4 = 20: 21 σειρές
        out (c),c
        ld bc,#BD14
        out (c),c
        ld bc,#BC07             ; R7 = 12: VSYNC στη γραμμή 240
        out (c),c
        ld bc,#BD0C
        out (c),c
        ld bc,#BC0C             ; R12/R13 = #C000 + scr_s
        out (c),c
        ld a,(scr_s + 1)
        and 3
        or #30
        inc b
        out (c),a
        dec b
        inc c
        out (c),c
        ld a,(scr_s)
        inc b
        out (c),a
        jr .out
.fa:    ld a,(split_on)         ; μέσα στο Α (σειρά ~4): το Α και το επόμενο Β
        or a
        jr z,.out
        ld bc,#BC04             ; R4 = 17: 18 σειρές
        out (c),c
        ld bc,#BD11
        out (c),c
        ld bc,#BC07             ; R7 = 127: κανένα VSYNC στο Α
        out (c),c
        ld bc,#BD7F
        out (c),c
        ld bc,#BC0C             ; R12/R13 = #4000: το HUD
        out (c),c
        ld bc,#BD10
        out (c),c
        ld bc,#BC0D
        out (c),c
        ld bc,#BD00
        out (c),c
        jr .out

; D = καταχωρητής, E = τιμή.
crtc_w: ld b,CRTC_SEL
        out (c),d
        ld b,CRTC_DAT
        out (c),e
        ret

; HL = μετατόπιση (λέξεις) -> ο πίνακας γραμμών (μόνο οι 144 του χάρτη).
; Δεν γράφει το scr_s: η κύλιση φτιάχνει πρώτα τον πίνακα, ζωγραφίζει τη
; λωρίδα, και δημοσιεύει τη μετατόπιση στο CRTC στο τέλος.
build_lines:
        add hl,hl               ; off = 2 * μετατόπιση
        ld b,h
        ld c,l
        ld hl,line_addr
        ld a,VIEW_H / 8
.row:   push af
        ld a,b                  ; η σειρά: off AND #7FF, στη σελίδα #C000
        and 7
        or #C0
        repeat 8
        ld (hl),c
        inc hl
        ld (hl),a
        inc hl
        add a,8
        rend
        ld a,c                  ; off += 80
        add a,80
        ld c,a
        jr nc,.nc
        inc b
.nc:    pop af
        dec a
        jr nz,.row
        ret

; Το HUD στην κύρια RAM #4000 (με τις τράπεζες στη θέση τους): οι 7 σειρές
; κάθε οκτάδας αποσυμπιέζονται στην οθόνη και πάνε στη θέση τους· τα
; υπόλοιπα μηδέν (οι σειρές 7-20 του καρέ Β φαίνονται: μαύρο).
HUD_ROWS    equ 7
hud_init:
        ld hl,hud_z
        ld de,SCREEN
        call dzx0
        ld hl,HUD_PAGE
        ld de,HUD_PAGE + 1
        ld bc,#3FFF
        ld (hl),0
        ldir
        ld hl,SCREEN
        ld de,HUD_PAGE
        ld a,8
.k:     ld bc,HUD_ROWS * 80
        ldir
        ex de,hl                ; DE += #800 - 560
        ld bc,#800 - HUD_ROWS * 80
        add hl,bc
        ex de,hl
        dec a
        jr nz,.k
        ld de,digits            ; και τα ψηφία, στις γραμμές που δεν φαίνονται
        ld bc,DIGITS_LEN
        ldir
        ret
