; jobmsg.asm — (2026-11-26) η δουλειά που πήρε ο χωρικός, για λίγο στην
; κορυφή του χάρτη, στη λωρίδα της ετικέτας των κουμπιών (ζήτημα του χρήστη:
; «όταν δίνω μία δουλειά σε χωρικό, γράφε την στην πάνω γραμμή για λίγο»).
;
; Το job_start (jobs.asm: RETURN πάνω σε πόρο) και το build_go (boot.asm:
; χτίσιμο, και η συνέχειά του) καλούν το jm_job / jm_bld στη θέση του
; «ld l,(ix+U_IDX)» τους: η δουλειά (J_KIND 0-3, ή 4 το χτίσιμο — μόνο του
; παίκτη) για JM_TIME καρέ μονάδων. Σε κάθε καρέ το hb_lab (ui_hud_i.asm) καλεί
; το jm_tick: όσο μετράει, και ο κέρσορας δεν είναι στα κουμπιά, το κείμενο
; (jm_tab: data/ui_q.asm από το src/make_ui.py, JOBS) με το hb_lblgo
; (ui_hud_d.asm) όπως η ετικέτα ενός κουμπιού, αλλά τα γράμματα μόνο όταν
; σβήνει η λωρίδα· στο τέλος, ή με την πρώτη κύλιση, η λωρίδα από τον
; καθρέφτη, μία γραμμή ανά καρέ, εκεί που την πήγε η κύλιση. Τα κουμπιά έχουν προτεραιότητα: όσο ο
; κέρσορας είναι εκεί ο χρόνος σταματάει, και η έξοδος (hb_off) ξαναφέρνει
; τον χάρτη — από κάτω η δουλειά ξανά, ως το τέλος του χρόνου της.
;
; ΧΩΡΟΣ: στη θέση του νεκρού κώδικα του M2 (tile_lookup, elem_lookup:
; scroll.asm· inc_de_scr, next_line_de: res.asm), που δεν τον καλούσε κανείς.

JM_TIME        equ 50              ; καρέ μονάδων (25 Hz): 2 s
JM_BG       equ #C0             ; = UI_BG (ui.asm: assert — στο snapshot δεν
                                ; συναρμολογείται)
JM_N        equ 11              ; τα γράμματα του μεγαλύτερου (make_ui.py:
                                ; assert): το κουτί, ίδιο για όλα
JM_X0       equ (80 - 3 * JM_N - 1) / 2  ; = το x του μεγαλύτερου (ακέραιο: το «/» του
                                ; rasm στρογγυλεύει)

jm_t:   db 0                    ; πόσα καρέ ακόμα (0: τίποτα)
jm_k:   db 0                    ; #10 + η δουλειά (για το hb_lw: ΜΕΤΑ το jm_t)
jm_y:   db 0                    ; η γραμμή της λωρίδας: την κουνάει η κάθετη
                                ; κύλιση (v_shy), με πρόσημο
jm_s:   db 0                    ; πόσα γράμματα μένουν να γραφτούν
jm_p:   dw 0                    ; το επόμενο
jm_x:   db 0                    ; και το byte του

; IX = χωρικός που πάει να χτίσει (και του αντιπάλου, bank7.asm) -> L =
; U_IDX. Χαλάει A, H.
jm_bld: ld a,(ix+U_TEAM)
        or a
        ld a,4
        jr z,jm_go
        ld l,(ix+U_IDX)
        ret

; IX = χωρικός της εντολής του παίκτη, cmd_kind = 0-3 -> L = U_IDX.
jm_job: ld a,(cmd_kind)
jm_go:  or #10
        ld h,a
        ld l,JM_TIME
        ld (jm_t),hl
        xor a
        ld (jm_y),a
        ld l,(ix+U_IDX)
        ret

; Από το hb_lab, με την C0 -> A = hb_on, ή 0 όταν η λωρίδα δεν είναι των
; κουμπιών.
jm_tick:
        ld a,(hb_on)
        or a
        ret nz                  ; τα κουμπιά
        ld hl,jm_t
        or (hl)
        ret z                   ; καμία δουλειά
        ld a,(v_shy)            ; η κύλιση (CRTC) πήρε τη λωρίδα μαζί της:
        ld b,a                  ; πού είναι τώρα
        ld a,(jm_y)
        add a,b
        ld (jm_y),a
        ld a,(v_shx)
        or b
        jr z,.n
        ld a,(hl)               ; κύλιση: κατευθείαν στο σβήσιμο (τα γράμματα
        cp 8                    ; ξανά, και οι γραμμές που άφησε πίσω η
        jr c,.n                 ; κάθετη, θα ήθελαν ~20 ms σε καρέ κύλισης)
        ld (hl),8
.n:     dec (hl)
        ld a,(hl)
        cp 8
        jr nc,.d
        ld hl,jm_y              ; τα 8 τελευταία καρέ: η λωρίδα από τον
        add a,(hl)              ; καθρέφτη, μία γραμμή σε κάθε καρέ (από
        cp VIEW_H               ; κάτω: ~1,5 ms η καθεμία — ολόκληρη μαζί
        jr nc,.x                ; ~12 ms, και με το units_forget του hb_off
        ld b,a                  ; το καρέ περνούσε τα 55 ms) — όχι έξω από
        ld c,0                  ; το παράθυρο (από πάνω: αρνητική). Μια
        ld de,80 * 256 + 1      ; μονάδα μέσα της σβήνεται ως την επόμενη
        call mirror_rect        ; κίνησή της.
.x:     ld a,255                ; hb_lw 255: η επόμενη ετικέτα σβήνει
        ld (hb_lw),a            ; ολόκληρη τη λωρίδα.
        xor a
        ret
.d:     cp JM_TIME - 2          ; όχι στο καρέ της εντολής (το πεδίο της
        jr nc,.z                ; πορείας, οι δουλειές), ούτε στο επόμενο
        ld hl,jm_k
        ld a,(hb_lw)            ; η λωρίδα δεν είναι πια δική της (η αρχή,
        cp (hl)                 ; άλλη δουλειά, τα κουμπιά): από την αρχή —
        jr z,.g                 ; σε αυτό το καρέ μόνο το κουτί (~3 ms)
        ld a,(hl)
        ld (hb_lw),a
        and 15
        ld hl,jm_tab
        call um_ptrn            ; HL = n, τα γράμματα
        ld a,(hl)
        ld (jm_s),a
        inc hl
        ld (jm_p),hl
        ld b,a                  ; στη μέση: (80 - 3 n) / 2, όπως το hb_lblgo
        add a,a
        add a,b
        neg
        add a,80
        srl a
        ld (jm_x),a
        ld bc,JM_X0             ; το κουτί: ίδιο για όλες (μια νέα σβήνει
        ld de,(3 * JM_N + 1) * 256 + 8  ; ολόκληρη την παλιά)
        ld a,JM_BG
        call ui_fill
        jr .z
.g:     ld hl,jm_s              ; ένα γράμμα σε κάθε καρέ (~1 ms: όλα μαζί
        ld a,(hl)               ; ~10 ms, πάνω σε καρέ μονάδων ως 38 ms
        or a                    ; περνούσαν τα 40)
        jr z,.z
        dec (hl)
        ld hl,(jm_p)
        ld a,(jm_x)
        ld c,a
        ld b,1
        call hb_lblg
        ld (jm_p),hl
        ld a,c
        ld (jm_x),a
.z:     xor a
        ret

        include "../data/ui_q.asm"
